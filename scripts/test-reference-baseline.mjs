import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {syncContent} from './sync-reference-baseline.mjs';
const read=p=>JSON.parse(readFileSync(p,'utf8'));
const mf=read('data/manifest.json'),keys=['tax','us','world','payroll','arizona'];
const values=Object.fromEntries(keys.map(k=>[k,read(mf[k].path)]));
const html=readFileSync('index.html','utf8');
assert.equal(syncContent(html,mf,values),html,'Inline fallback must equal current verified datasets');
assert.equal(syncContent(syncContent(html,mf,values),mf,values),html,'Sync must be idempotent');
const future=structuredClone(values);
for(const k of ['tax','payroll','arizona'])future[k].taxYear+=1;
future.tax.values.single.ded+=100;
future.payroll.socialSecurityWageBase+=7800;
future.arizona.standardDeduction.single+=250;
const nextManifest=structuredClone(mf);
for(const k of ['tax','payroll','arizona'])nextManifest[k].year+=1;
const futureHtml=syncContent(html,nextManifest,future);
assert(futureHtml.includes('"taxYear":'+future.tax.taxYear),'Updated tax baseline must be embedded');
assert(futureHtml.includes('"socialSecurityWageBase":'+future.payroll.socialSecurityWageBase),'Updated SSA value must be embedded');
assert(futureHtml.includes('"single":'+future.arizona.standardDeduction.single),'Updated Arizona baseline must be embedded');
assert.equal(syncContent(futureHtml,nextManifest,future),futureHtml,'Updated defaults must be stable');
assert(futureHtml.includes('function updateReferenceYearLabels()'),'Other application code must survive regeneration');
const invalid=structuredClone(nextManifest);invalid.payroll.year-=1;
assert.throws(()=>syncContent(html,invalid,future),'Never embed mismatched tax-year source');
assert(html.includes("if(node.parentElement?.closest('script,style,#earningsYearsNotice,#taxYearsNotice'))continue;"),'Dynamic notice must not be translated twice');
assert(html.includes("$('#earningsYearsNotice').textContent=lang==='en'"),'Earnings notice must select English explicitly');
console.log('PASS: inline baseline synchronization, future-year change, idempotence and notice translation guards');
