import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const s=readFileSync('index.html','utf8');
for(const id of ['referenceAudit','referenceAuditGrid','referenceAuditTitle','referenceAuditHint'])assert(s.includes('id="'+id+'"'),'Missing '+id);
assert(s.includes('function renderReferenceAudit()'),'Missing audit display');
assert(s.includes('async function loadReferenceAudit()'),'Missing async audit lookup');
assert(s.includes("if(REFERENCE_AUDIT.started)return"),'API should not be repeatedly fetched');
assert(s.includes("$('#referenceStatusPanel').open)loadReferenceAudit()"),'Only fetch when panel opens');
assert(s.includes("branch=main&per_page=1"),'Query latest main run');
assert(s.includes("controller.abort(),6500"),'Bounded API timeout');
assert(s.includes("if(!response.ok)throw Error"),'HTTP errors handled');
assert(s.includes("REFERENCE_AUDIT.results[workflow.id]={error:true}"),'Handle unavailable GitHub API');
const auditRenderer=s.slice(s.indexOf('function renderReferenceAudit(){'),s.indexOf('async function loadReferenceAudit(){'));
assert(!auditRenderer.includes('View run')&&!auditRenderer.includes('actions/runs/')&&!auditRenderer.includes("document.createElement('a')"),'Public audit cards must not expose workflow run links');
assert(auditRenderer.includes('run.updated_at||run.created_at'),'Keep last execution time');
assert(auditRenderer.includes("state==='success'"),'Keep validation status');
assert(s.includes("function refreshLanguage(){renderReferenceStatus();renderReferenceAudit();"),'Language changes update audit text');
assert(s.includes('const REFERENCE_DATA=await loadReferenceData();'),'No changes to baseline loading');
assert(s.includes('if(!value){value=REFERENCE_BASELINE[k]'),'Offline fallback still present');
console.log('PASS: lazy CI audit status, safe links, error fallback, translation, and loader');
