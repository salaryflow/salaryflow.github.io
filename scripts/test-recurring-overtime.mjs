import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const html=readFileSync('index.html','utf8');
const helpers=html.slice(html.indexOf('const num=('),html.indexOf('const TAX_STATES='));
assert(helpers.includes('function setWeeklyOvertime('));
assert(helpers.includes('function overtimeWindows('));
assert(html.includes('const otAllWindows=overtimeWindows(j,historyStart,dayS+48*3600)'),'Overtime windows should be compiled once per day/revision');
assert(html.includes('const otLiveWindows=otAllWindows.filter('),'Live overtime windows should be derived from cached history');
assert(html.includes('overtimeAccrued(weekS,dayS,j,otRate,otAllWindows).money'),'Weekly totals should count cached recurring overtime');
const ctx={config:{mode:'gross'},annualNet:()=>78000};
vm.createContext(ctx);
vm.runInContext(helpers+';globalThis.api={overtimeDate,overtimeWindows,overtimeAccrued,overtimeForDate,setWeeklyOvertime,currentWeeklyOvertime,weeklyOvertimeRule,overtimeWindow};',ctx);
const {overtimeDate,overtimeWindows,overtimeAccrued,overtimeForDate,setWeeklyOvertime,currentWeeklyOvertime,weeklyOvertimeRule}=ctx.api;
const job={gross:104000,hours:8,weekdays:[1,2,3,4,5],start:'09:00',breakMode:'unpaid',breakMinutes:60,breakStart:'12:00',overtimeRecords:{},overtimeWeeklyRules:[]};
const date=(day,hour=0)=>new Date(2026,10,day,hour).getTime()/1000;
const tick=(day,hour=0)=>new Date(2026,10,day,hour);
const near=(a,b,m)=>assert(Math.abs(a-b)<1e-5,m+': '+a+' != '+b);
assert(!overtimeForDate(job,tick(4)).enabled,'Recurring OT defaults OFF');
setWeeklyOvertime(job,{enabled:true,weekdays:[1,3,5],hours:2,startTime:'18:30',multiplier:1.5},tick(2));
assert(overtimeForDate(job,tick(2)).enabled,'Monday is recurring');
assert(overtimeForDate(job,tick(4)).enabled,'Wednesday is recurring');
assert(!overtimeForDate(job,tick(5)).enabled,'Thursday is off');
assert(overtimeForDate(job,tick(6)).enabled,'Friday is recurring');
const windows=overtimeWindows(job,date(2),date(9));
assert.equal(windows.length,3,'Mon/Wed/Fri over the week, no manual logging');
near(overtimeAccrued(date(2),date(9),job).money,3*2*75,'Three 2h shifts at 1.5x');
near(overtimeAccrued(date(4,18),date(4,19),job).money,37.5,'Only half hour from 18:30 to 19:00');
assert.equal(overtimeAccrued(date(2),date(9),job).seconds,6*3600,'Automatic overtime hours retained even when browser was closed');
job.overtimeRecords['2026-11-04']={enabled:true,startTime:'20:00',hours:1,multiplier:2};
near(overtimeAccrued(date(2),date(9),job).money,2*2*75+100,'Manual Wednesday entry must replace recurring rule, not add to it');
job.overtimeRecords['2026-11-04']={enabled:false,hours:0,multiplier:1.5};
near(overtimeAccrued(date(2),date(9),job).money,2*2*75,'Manual OFF is an exclusion');
delete job.overtimeRecords['2026-11-04'];
setWeeklyOvertime(job,{hours:1,multiplier:2},tick(5));
assert.equal(weeklyOvertimeRule(job,tick(4)).hours,2,'Edits do not rewrite prior weekly rules');
assert.equal(weeklyOvertimeRule(job,tick(6)).hours,1,'Future days use updated rule');
near(overtimeAccrued(date(2),date(9),job).money,2*2*75+1*100,'Historical recurring totals honor date-effective changes');
setWeeklyOvertime(job,{enabled:false},tick(7));
assert(!overtimeForDate(job,tick(9)).enabled,'Turning off recurring disables future dates');
assert.equal(overtimeWindows(job,date(9),date(16)).length,0,'No future money when switched OFF');
near(overtimeAccrued(date(2),date(9),job).money,2*2*75+100,'Stopping recurring preserves previously accrued history');
// Switch UI saved today's override must not create retroactive records for earlier days.
const noHistory={...job,overtimeRecords:{},overtimeWeeklyRules:[]};
setWeeklyOvertime(noHistory,{enabled:true,weekdays:[3],hours:2,startTime:'18:30',multiplier:1.5},tick(4));
assert.equal(overtimeWindows(noHistory,date(2),date(4)).length,0,'Enabling today must not backfill past days');
assert.equal(overtimeWindows(noHistory,date(4),date(5)).length,1,'Enabling today counts today');
// Local-week and month boundary calculations share the same dated windows.
const monthRule={...job,overtimeRecords:{},overtimeWeeklyRules:[]};
setWeeklyOvertime(monthRule,{enabled:true,weekdays:[0],hours:2,startTime:'22:00',multiplier:2},new Date(2026,9,25));
near(overtimeAccrued(new Date(2026,10,1).getTime()/1000,date(3),monthRule).money,200,'November boundary counts Sunday 2h OT');
const recurringDate=tick(6);
assert.equal(overtimeDate(recurringDate),'2026-11-06');
console.log('PASS: recurring weekdays, 1.5/2x, browser-closed accrual, current periods, rule history, manual exceptions, stop future accrual');
