// An isolated dry-run of the PR preparation logic; never modifies tracked data.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync,mkdtempSync,rmSync,copyFileSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
const base=new URL('../',import.meta.url);
const root=mkdtempSync(join(tmpdir(),'salaryflow-review-test-'));
const copy=(from,to)=>{
 const dest=join(root,to);
 mkdirSync(dest.slice(0,dest.lastIndexOf('/')),{recursive:true});
 copyFileSync(new URL(from,base),dest);
};
const output=join(root,'decision.txt');
const run=()=>{writeFileSync(output,'');return spawnSync(process.execPath,['scripts/prepare-data-pr.mjs','tax','2027'],{cwd:root,encoding:'utf8',env:{...process.env,GITHUB_OUTPUT:output}})};
const decision=()=>readFileSync(output,'utf8').trim();
try{
 copy('scripts/prepare-data-pr.mjs','scripts/prepare-data-pr.mjs');
 copy('data/manifest.json','data/manifest.json');
 for(const file of ['tax-2026.json','income-us-2026.json','income-world-2024.json'])copy('data/'+file,'data/'+file);
 const tax=JSON.parse(readFileSync(join(root,'data/tax-2026.json'),'utf8'));
 mkdirSync(join(root,'candidates'),{recursive:true});
 const target=join(root,'candidates/tax-2027.json');
 const candidate=structuredClone(tax);
 candidate.taxYear=2027;
 candidate.source='https://www.irs.gov/irb/2026-45_IRB';
 candidate.retrieval='TEST ONLY: synthetic +2% thresholds, not real IRS values';
 for(const v of Object.values(candidate.values)){
  v.ded=Math.round(v.ded*1.02);
  v.br=v.br.map(x=>Math.round(x*1.02));
 }
 writeFileSync(target,JSON.stringify(candidate));
 let result=run();
 assert.equal(result.status,0,result.stderr||result.stdout);
 assert(existsSync(join(root,'data/tax-2027.json')));
 const manifest=JSON.parse(readFileSync(join(root,'data/manifest.json')));
 assert.equal(manifest.tax.year,2027);
 assert.equal(manifest.tax.path,'data/tax-2027.json');
 assert(readFileSync(join(root,'data-review-report.md'),'utf8').includes('largest changes'));
 assert.equal(decision(),'auto_safe=true','Small official IRS change must be auto-eligible');
 copy('data/manifest.json','data/manifest.json');
 candidate.values.single.br[0]=Math.round(tax.values.single.br[0]*1.20);
 writeFileSync(target,JSON.stringify(candidate));
 result=run();
 assert.equal(result.status,0,result.stderr||result.stdout);
 assert.equal(decision(),'auto_safe=false','Large IRS change must require manual review');
 copy('data/manifest.json','data/manifest.json');
 candidate.values.single.br[0]=Math.round(tax.values.single.br[0]*1.02);
 candidate.source='https://some-unverified-domain.example/irs';
 writeFileSync(target,JSON.stringify(candidate));
 result=run();
 assert.equal(result.status,0,result.stderr||result.stdout);
 assert.equal(decision(),'auto_safe=false','Non-IRS sources must require manual review');
 // Verified DQYDJ candidates under 25% now auto-merge; large shifts must stop.
 const runKind=(kind,year)=>{writeFileSync(output,'');return spawnSync(process.execPath,['scripts/prepare-data-pr.mjs',kind,String(year)],{cwd:root,encoding:'utf8',env:{...process.env,GITHUB_OUTPUT:output}})};
 copy('data/manifest.json','data/manifest.json');
 const prevUS=JSON.parse(readFileSync(join(root,'data/income-us-2026.json'),'utf8'));
 const nextUS=structuredClone(prevUS);
 nextUS.editionYear=2027;nextUS.incomeYear=2026;
 nextUS.source='https://dqydj.com/income-by-state/';
 nextUS.retrieval='TEST ONLY: verified synthetic DQYDJ increment';
 for(const [code,a] of Object.entries(nextUS.values))nextUS.values[code]=a.map(v=>Math.round(v*1.02));
 writeFileSync(join(root,'candidates/us-2027.json'),JSON.stringify(nextUS));
 result=runKind('us',2027);
 assert.equal(result.status,0,result.stderr||result.stdout);
 assert.equal(decision(),'auto_safe=true','Small official DQYDJ update should be auto-eligible');
 copy('data/manifest.json','data/manifest.json');
 nextUS.values.AZ[3]=Math.round(prevUS.values.AZ[3]*1.5);
 writeFileSync(join(root,'candidates/us-2027.json'),JSON.stringify(nextUS));
 result=runKind('us',2027);
 assert.equal(result.status,0,result.stderr||result.stdout);
 assert.equal(decision(),'auto_safe=false','Anomalous DQYDJ change must block auto-merge');
 copy('data/manifest.json','data/manifest.json');
 const prevWorld=JSON.parse(readFileSync(join(root,'data/income-world-2024.json'),'utf8'));
 const nextWorld=structuredClone(prevWorld);
 nextWorld.incomeYear=2025;nextWorld.source='https://wid.world/data/';
 nextWorld.retrieval='TEST ONLY: verified synthetic WID inflation adjustment';
 for(const record of Object.values(nextWorld.values))record.points=record.points.map(v=>Math.round(v*1.03));
 writeFileSync(join(root,'candidates/world-2025.json'),JSON.stringify(nextWorld));
 result=runKind('world',2025);
 assert.equal(result.status,0,result.stderr||result.stdout);
 assert.equal(decision(),'auto_safe=true','Small official WID update should be auto-eligible');
 copy('data/manifest.json','data/manifest.json');
 nextWorld.source='https://unverified.example/data';
 writeFileSync(join(root,'candidates/world-2025.json'),JSON.stringify(nextWorld));
 result=runKind('world',2025);
 assert.equal(result.status,0,result.stderr||result.stdout);
 assert.equal(decision(),'auto_safe=false','Untrusted WID source must block auto-merge');
 copy('data/manifest.json','data/manifest.json');
 // Malformed proposal should fail before modifying the published reference manifest.
 copy('data/manifest.json','data/manifest.json');
 candidate.values.single.br=[1,2,3];
 writeFileSync(target,JSON.stringify(candidate));
 result=run();
 assert.notEqual(result.status,0,'Malformed candidate must be rejected');
 assert.equal(JSON.parse(readFileSync(join(root,'data/manifest.json'))).tax.year,2026);
 console.log('PASS: synthetic candidate generates versioned JSON and review report');
 console.log('PASS: official IRS, DQYDJ and WID small changes auto-eligible, anomalous and unverified changes require review');
 console.log('PASS: malformed candidate rejected without manifest changes');
}finally{rmSync(root,{recursive:true,force:true})}
